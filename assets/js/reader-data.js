(function(root){
  'use strict';
  // The editor owns the complete archive. The reader needs only display/search fields.
  const fields=['id','term','letter','source_index','language_raw','languages','word_type','word_type_label','definition','editorial_meaning','translations','related','equivalent_ids','source_url','source_label','images','external_links'];
  function dictionary(data){
    const Content=typeof module!=='undefined'&&module.exports?require('./entry-content.js'):root.KamusContent;
    return {metadata:data.metadata,sources:data.sources.map(({url,letter,published})=>({url,letter,published})),entries:data.entries.map(entry=>{
      const out=Object.fromEntries(fields.filter(key=>entry[key]!==undefined).map(key=>[key,entry[key]]));
      const meaning=Content.meaning(entry);
      if(meaning?.provider==='kbbi_iii'){
        const {multiple,wordTypes,tags,items}=meaning.layout;
        out.reading={term:entry.term,label:meaning.label,provider:meaning.provider,layout:{multiple,wordTypes,tags:tags.map(({label})=>({label})),items:items.map(({term,homonym,pronunciation,wordTypes,senses})=>({term,homonym,pronunciation,wordTypes,senses:senses.map(({number,text,wordTypes})=>({number,text,wordTypes}))}))}};
      }
      return out;
    })};
  }
  // Row schema and shared language/URL tables remove repeated JSON keys and strings.
  function packDictionary(data){
    const out=dictionary(data),languages=[],urls=[],intern=(list,value)=>{const key=JSON.stringify(value),i=list.findIndex(x=>JSON.stringify(x)===key);return i<0?list.push(value)-1:i;};
    const keys=[...fields,'reading'].filter(key=>out.entries.some(entry=>Object.hasOwn(entry,key)));
    return {metadata:out.metadata,sources:out.sources,languages,urls,fields:keys,rows:out.entries.map(entry=>keys.map(key=>{
      const value=entry[key];
      if(key==='languages')return value.map(l=>intern(languages,l));
      if(key==='translations')return value.map(t=>[t.terms,t.languages.map(l=>intern(languages,l))]);
      if(key==='source_url')return intern(urls,value||'');
      return value??null;
    }))};
  }
  function expandDictionary(packed){
    return {metadata:packed.metadata,sources:packed.sources,entries:packed.rows.map(row=>Object.fromEntries(packed.fields.flatMap((key,i)=>{
      let value=row[i];if(value===null)return [];
      if(key==='languages')value=value.map(i=>packed.languages[i]);
      if(key==='translations')value=value.map(([terms,languages])=>({terms,languages:languages.map(i=>packed.languages[i])}));
      if(key==='source_url')value=packed.urls[value];
      return [[key,value]];
    })))};
  }
  function packAssociations(data,associations){
    const ids=new Map(data.entries.map((entry,i)=>[entry.id,i]));
    return {categories:associations.categories,themes:associations.themes,
      byEntry:data.entries.map(entry=>{const a=associations.byEntry[entry.id];return [a.primary,a.themes,a.categories];}),
      edges:associations.edges.map(edge=>[ids.get(edge.source),ids.get(edge.target),edge.score])};
  }
  function expandAssociations(data,packed){
    const ids=data.entries.map(entry=>entry.id);
    return {categories:packed.categories,themes:packed.themes,
      byEntry:Object.fromEntries(packed.byEntry.map(([primary,themes,categories],i)=>[ids[i],{primary,themes,categories}])),
      edges:packed.edges.map(([source,target,score])=>({source:ids[source],target:ids[target],score}))};
  }
  function script(data,associations){
    return '/* Generated by tools/build-reader.cjs. Edit dictionary.json, not this file. */\nwindow.DICTIONARY_DATA = KamusReaderData.expandDictionary('+JSON.stringify(packDictionary(data))+');\nwindow.KAMUS_ASSOCIATIONS = KamusReaderData.expandAssociations(window.DICTIONARY_DATA, '+JSON.stringify(packAssociations(data,associations))+');\n';
  }
  const api={dictionary,packDictionary,expandDictionary,packAssociations,expandAssociations,script};
  if(typeof module!=='undefined'&&module.exports)module.exports=api;else root.KamusReaderData=api;
})(typeof window==='undefined'?globalThis:window);
